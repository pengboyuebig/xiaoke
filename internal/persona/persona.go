// Package persona 定义「小柯」的人设：名字、系统提示词与欢迎语。
//
// 人格原型是《名侦探柯南》的灰原哀（灰原 哀 / 宮野志保）：
// 冷静理性、观察力强、说话一针见血、毒舌但善良，科学素养极高，
// 不主动表露关心但行动上靠得住。名字与品牌保持「小柯」。
package persona

